#!/bin/bash
set -e

MOODLE_DIR=/var/www/moodle
MOODLEDATA_DIR=/var/www/moodledata

# Fail loudly on missing configuration rather than installing something wrong.
: "${MOODLE_WWWROOT:?MOODLE_WWWROOT must be set (e.g. https://moodle.example.com)}"
: "${MOODLE_DATABASE_HOST:?MOODLE_DATABASE_HOST must be set}"
: "${MOODLE_DATABASE_NAME:?MOODLE_DATABASE_NAME must be set}"
: "${MOODLE_DATABASE_USER:?MOODLE_DATABASE_USER must be set}"

MOODLE_DATABASE_PORT_NUMBER="${MOODLE_DATABASE_PORT_NUMBER:-3306}"
MOODLE_SSLPROXY="${MOODLE_SSLPROXY:-false}"
MOODLE_SITE_FULLNAME="${MOODLE_SITE_FULLNAME:-Moodle}"
MOODLE_SITE_SHORTNAME="${MOODLE_SITE_SHORTNAME:-moodle}"
MOODLE_ADMIN_USER="${MOODLE_ADMIN_USER:-admin}"
MOODLE_ADMIN_EMAIL="${MOODLE_ADMIN_EMAIL:-admin@example.com}"

echo "Waiting for MariaDB at $MOODLE_DATABASE_HOST:$MOODLE_DATABASE_PORT_NUMBER..."
until mysqladmin ping -h"$MOODLE_DATABASE_HOST" --protocol=tcp --skip-ssl --silent; do
  sleep 2
done

# Moodle's code is baked into the image at $MOODLE_DIR and the DocumentRoot
# symlink is created at build time, so there is nothing to place on a volume
# here. Only moodledata is persistent.
echo "Moodle $(awk -F\' '/^\$release/ {print $2; exit}' "$MOODLE_DIR/public/version.php") from image"

# ---------------------------------------------------------------------------
# config.php, written on every start.
#
# Written BEFORE the SKIP_INSTALL check on purpose. Every container that runs
# Moodle code needs its own config.php, because containers in a pod share
# volumes but not their filesystems — and Moodle's code now lives in the image
# layer, not on a volume. The cron container therefore runs this entrypoint with
# SKIP_INSTALL=true: it gets a config.php and waits for the database, but leaves
# installing and upgrading to the web container.
#
# The values are read by PHP from the environment at request time, so this file
# is identical in every deployment and the hostname is never baked in. That is
# what lets the same image run behind any ingress, in any cluster.
# ---------------------------------------------------------------------------
echo "Writing config.php (wwwroot=$MOODLE_WWWROOT sslproxy=$MOODLE_SSLPROXY)..."
cat > "$MOODLE_DIR/config.php" <<'PHP'
<?php
// Generated by docker-entrypoint.sh on container start. Do not edit by hand —
// changes are overwritten. Configure via environment variables instead.

unset($CFG);
global $CFG;
$CFG = new stdClass();

$CFG->dbtype    = 'mariadb';
$CFG->dblibrary = 'native';
$CFG->dbhost    = getenv('MOODLE_DATABASE_HOST');
$CFG->dbname    = getenv('MOODLE_DATABASE_NAME');
$CFG->dbuser    = getenv('MOODLE_DATABASE_USER');
$CFG->dbpass    = getenv('MOODLE_DATABASE_PASSWORD');
$CFG->prefix    = 'mdl_';
$CFG->dboptions = [
    'dbpersist'   => 0,
    'dbport'      => getenv('MOODLE_DATABASE_PORT_NUMBER'),
    'dbsocket'    => '',
    'dbcollation' => 'utf8mb4_unicode_ci',
];

$CFG->wwwroot  = rtrim(getenv('MOODLE_WWWROOT'), '/');
$CFG->dataroot = '/var/www/moodledata';
$CFG->admin    = 'admin';

$CFG->directorypermissions = 02777;

// Required when TLS terminates at an ingress or load balancer. Without it
// Moodle sees plain HTTP on the backend, decides the site is http://, and
// redirect-loops against an https:// wwwroot.
if (getenv('MOODLE_SSLPROXY') === 'true') {
    $CFG->sslproxy = true;
}

require_once(__DIR__ . '/lib/setup.php'); // Do not edit
PHP

chown www-data:www-data "$MOODLE_DIR/config.php"
chmod 640 "$MOODLE_DIR/config.php"

if [ "$SKIP_INSTALL" = "true" ]; then
    echo "SKIP_INSTALL set — config.php written, skipping install/upgrade."
    exec "$@"
fi

# ---------------------------------------------------------------------------
# Install the database if empty, otherwise apply any pending upgrade.
#
# install_database.php rather than install.php, because install.php writes its
# own config.php — the behaviour we deliberately removed above.
#
# The upgrade branch is what makes a new image take effect: a newer Moodle in
# the image against an older schema is detected and migrated here.
# ---------------------------------------------------------------------------
echo "Checking if Moodle database is already configured..."
if ! mysql -h"$MOODLE_DATABASE_HOST" \
    -u"$MOODLE_DATABASE_USER" \
    -p"$MOODLE_DATABASE_PASSWORD" \
    --skip-ssl \
    -e "SELECT 1 FROM mdl_user LIMIT 1;" "$MOODLE_DATABASE_NAME" >/dev/null 2>&1; then

    : "${MOODLE_ADMIN_PASSWORD:?MOODLE_ADMIN_PASSWORD must be set for first install}"

    echo "No Moodle tables found — installing database..."
    php "$MOODLE_DIR/admin/cli/install_database.php" \
      --agree-license \
      --fullname="$MOODLE_SITE_FULLNAME" \
      --shortname="$MOODLE_SITE_SHORTNAME" \
      --adminuser="$MOODLE_ADMIN_USER" \
      --adminpass="$MOODLE_ADMIN_PASSWORD" \
      --adminemail="$MOODLE_ADMIN_EMAIL"
else
    echo "Moodle database present — applying any pending upgrade..."
    php "$MOODLE_DIR/admin/cli/upgrade.php" --non-interactive
fi

exec "$@"
